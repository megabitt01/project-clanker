"""Generates runtime/kernel/kfuncs.h: prototypes for every KEXPORT definition.

Run after adding a kernel export:  python tools/gen_kfuncs.py
"""
import glob, os, re

here = os.path.dirname(os.path.abspath(__file__))
kdir = os.path.join(here, '..', 'runtime', 'kernel')
pat = re.compile(r'^(KEXPORT(?:_FASTCALL)?\([^)]*\))\s*(kx_\w+)\s*\(', re.M)
out = ['// Generated by tools/gen_kfuncs.py - do not edit.', '#pragma once', '#include "kexports.h"',
       '#include <windows.h>', 'namespace rt { struct XbeSectionHeader; }', 'using rt::XbeSectionHeader;', '']
for path in sorted(glob.glob(os.path.join(kdir, '*.cpp'))):
    src = open(path, encoding='utf-8').read()
    for m in pat.finditer(src):
        # capture the full parameter list, honouring nested parentheses
        i, depth = m.end(), 1
        while depth:
            depth += {'(': 1, ')': -1}.get(src[i], 0)
            i += 1
        params = ' '.join(src[m.end():i - 1].split())
        out.append(f'{m.group(1)} {m.group(2)}({params});')
out.append('extern "C" uint32_t __cdecl kx_DbgPrint(const char *Format, ...);')
open(os.path.join(kdir, 'kfuncs.h'), 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print(len(out) - 7, 'prototypes')
