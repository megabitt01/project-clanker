struct KelvinDynamic {
    uint32_t program[NV2A_MAX_TRANSFORM_PROGRAM_LENGTH][4];
    uint32_t program_load = 0;
    uint32_t program_start = 0;
    uint64_t program_generation = 1;  // bumped whenever program words change
    float constants[NV2A_VERTEXSHADER_CONSTANTS][4];
    uint32_t constant_load = 0;
    bool constants_dirty = true;
    float current_attr[NV2A_VERTEXSHADER_ATTRIBUTES][4];  // immediate-mode / default values

    // Draw batch collected between BEGIN and END.
    uint32_t primitive = 0;
    std::vector<uint32_t> inline_array;     // INLINE_ARRAY dwords
    std::vector<uint32_t> inline_elements;  // ARRAY_ELEMENT16/32 indices
    std::vector<uint32_t> draw_arrays;      // (start, count) pairs
    std::vector<float> immediate;           // SET_VERTEX_DATA* vertices (16 attrs x 4 floats each)
};
extern KelvinDynamic g_kd;

