// Raw method storage: k[method / 4] holds the last value written to every
// Kelvin method. Most state is decoded from here at draw time.
extern uint32_t k[0x2000 / 4];
inline uint32_t &kr(uint32_t method) { return k[method >> 2]; }
inline float kf(uint32_t method)
{
    union { uint32_t u; float f; } c;
    c.u = k[method >> 2];
    return c.f;
}

